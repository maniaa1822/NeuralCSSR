#!/usr/bin/env python3
"""
Utility script to organize JS analysis results into the proper directory structure.

This script moves PNG files generated by plot_js_vs_L.py from model checkpoint
directories into the organized experiments/js_analysis/ structure.
"""

import os
import shutil
from pathlib import Path
import re
import argparse


def categorize_file(filename: str) -> tuple[str, str]:
    """
    Categorize a JS analysis PNG file by preset and analysis type.

    Returns:
        (preset, analysis_type) tuple
    """
    # Extract preset
    preset = None
    if 'golden_mean' in filename:
        preset = 'golden_mean'
    elif 'seven_state' in filename:
        preset = 'seven_state_human'
    elif 'even_process' in filename:
        preset = 'even_process'
    else:
        preset = 'custom_models'

    # Extract analysis type
    analysis_type = None
    if 'instate' in filename:
        analysis_type = 'instate_analysis'
    elif 'cross_state' in filename:
        analysis_type = 'cross_state_analysis'
    elif 'optimal_L' in filename:
        analysis_type = 'optimal_L_analysis'
    elif 'cond_' in filename and '_k' in filename and 'k0' not in filename:
        # Conditional k-step analysis (both random pairs and cross-state)
        if 'cross_state' not in filename:
            analysis_type = 'k_step_analysis'  # Conditional random pairs
        else:
            analysis_type = 'cross_state_analysis'  # Conditional cross-state
    elif '_k' in filename and 'k0' not in filename and 'cross_state' not in filename:
        # Regular k-step analysis, but not cross-state (which is handled above)
        analysis_type = 'k_step_analysis'
    else:
        analysis_type = 'random_pairs'

    return preset, analysis_type


def organize_results(source_dirs: list[str], target_base: str, dry_run: bool = False):
    """
    Organize JS analysis results from source directories into target structure.

    Args:
        source_dirs: List of directories to search for PNG files
        target_base: Base target directory (experiments/js_analysis)
        dry_run: If True, only print what would be done
    """
    target_path = Path(target_base)

    # Pattern to match JS analysis PNG files
    js_pattern = re.compile(r'.*_(js_histograms|js_thresholds_vs_L|instate_js|cross_state|optimal_L_analysis).*\.png$')

    moved_files = 0

    for source_dir in source_dirs:
        source_path = Path(source_dir)
        if not source_path.exists():
            print(f"Warning: Source directory {source_dir} does not exist")
            continue

        print(f"Scanning {source_dir}...")

        # Find all PNG files that match JS analysis pattern
        for png_file in source_path.glob("*.png"):
            if js_pattern.match(png_file.name):
                preset, analysis_type = categorize_file(png_file.name)

                # Determine target directory
                target_dir = target_path / preset / analysis_type
                target_file = target_dir / png_file.name

                print(f"  {png_file.name} -> {preset}/{analysis_type}/")

                if not dry_run:
                    # Create target directory if it doesn't exist
                    target_dir.mkdir(parents=True, exist_ok=True)

                    # Move the file
                    try:
                        shutil.move(str(png_file), str(target_file))
                        moved_files += 1
                    except Exception as e:
                        print(f"    Error moving file: {e}")
                else:
                    moved_files += 1

    if dry_run:
        print(f"\nDry run complete. Would move {moved_files} files.")
    else:
        print(f"\nMoved {moved_files} files to organized structure.")


def main():
    parser = argparse.ArgumentParser(description='Organize JS analysis results')
    parser.add_argument('--source-dirs', nargs='+',
                       default=['nanoGPT/out-golden-mean-char',
                               'nanoGPT/out-seven-state-char',
                               'nanoGPT/out-even-process-char'],
                       help='Directories to search for PNG files')
    parser.add_argument('--target', default='experiments/js_analysis',
                       help='Target base directory')
    parser.add_argument('--dry-run', action='store_true',
                       help='Show what would be done without moving files')

    args = parser.parse_args()

    # Get repository root
    repo_root = Path(__file__).parent.parent.parent

    # Convert relative paths to absolute
    source_dirs = [str(repo_root / path) for path in args.source_dirs]
    target_base = str(repo_root / args.target)

    organize_results(source_dirs, target_base, args.dry_run)


if __name__ == '__main__':
    main()